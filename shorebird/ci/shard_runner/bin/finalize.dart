/// Production storage bucket.
const productionBucket = 'gs://download.shorebird.dev';

/// Uploads artifacts to the production GCS bucket.
Future<void> uploadToProduction({
  required String engineSrc,
  required String engineRevision,
  required String? contentHash,
}) async {
  final outDir = p.join(engineSrc, 'out');
  final infraRoot = '$productionBucket/flutter_infra_release/flutter/$engineRevision';
  final mavenRoot = '$productionBucket/download.flutter.io/io/flutter';
  final mavenVer = '1.0.0-$engineRevision';
  final shorebirdRoot = '$productionBucket/shorebird/$engineRevision';

  // Content-hash root for Dart SDK (allows sharing across branches)
  final contentInfraRoot = contentHash != null
      ? '$productionBucket/flutter_infra_release/flutter/$contentHash'
      : null;

  // Helper to run gsutil cp
  Future<void> gscp(String src, String dest) async {
    print('[Upload] $src -> $dest');
    final result = await Process.run('gsutil', ['cp', src, dest]);
    if (result.exitCode != 0) {
      print('[Warning] gsutil cp failed: ${result.stderr}');
    }
  }

  // =========================================================================
  // Linux artifacts (from android-arm64, android-arm32, android-x64, host)
  // =========================================================================

  // Android Arm64 release Flutter artifacts
  var archOut = p.join(outDir, 'android_release_arm64');
  var zipsOut = p.join(archOut, 'zip_archives', 'android-arm64-release');
  var zipsDest = '$infraRoot/android-arm64-release';
  await gscp(p.join(zipsOut, 'artifacts.zip'), '$zipsDest/artifacts.zip');
  await gscp(p.join(zipsOut, 'linux-x64.zip'), '$zipsDest/linux-x64.zip');
  await gscp(p.join(zipsOut, 'symbols.zip'), '$zipsDest/symbols.zip');
  // Maven
  var archPath = p.join(archOut, 'arm64_v8a_release');
  var mavenPath = '$mavenRoot/arm64_v8a_release/$mavenVer/arm64_v8a_release-$mavenVer';
  await gscp('$archPath.pom', '$mavenPath.pom');
  await gscp('$archPath.jar', '$mavenPath.jar');
  await gscp('$archPath.maven-metadata.xml', '$mavenPath.maven-metadata.xml');

  // Android Arm32 release Flutter artifacts
  archOut = p.join(outDir, 'android_release');
  zipsOut = p.join(archOut, 'zip_archives', 'android-arm-release');
  zipsDest = '$infraRoot/android-arm-release';
  await gscp(p.join(zipsOut, 'artifacts.zip'), '$zipsDest/artifacts.zip');
  await gscp(p.join(zipsOut, 'linux-x64.zip'), '$zipsDest/linux-x64.zip');
  await gscp(p.join(zipsOut, 'symbols.zip'), '$zipsDest/symbols.zip');
  // Maven
  archPath = p.join(archOut, 'armeabi_v7a_release');
  mavenPath = '$mavenRoot/armeabi_v7a_release/$mavenVer/armeabi_v7a_release-$mavenVer';
  await gscp('$archPath.pom', '$mavenPath.pom');
  await gscp('$archPath.jar', '$mavenPath.jar');
  await gscp('$archPath.maven-metadata.xml', '$mavenPath.maven-metadata.xml');
  // flutter_embedding_release (from android_release)
  archPath = p.join(archOut, 'flutter_embedding_release');
  mavenPath = '$mavenRoot/flutter_embedding_release/$mavenVer/flutter_embedding_release-$mavenVer';
  await gscp('$archPath.pom', '$mavenPath.pom');
  await gscp('$archPath.jar', '$mavenPath.jar');
  await gscp('$archPath.maven-metadata.xml', '$mavenPath.maven-metadata.xml');

  // Android x64 release Flutter artifacts
  archOut = p.join(outDir, 'android_release_x64');
  zipsOut = p.join(archOut, 'zip_archives', 'android-x64-release');
  zipsDest = '$infraRoot/android-x64-release';
  await gscp(p.join(zipsOut, 'artifacts.zip'), '$zipsDest/artifacts.zip');
  await gscp(p.join(zipsOut, 'linux-x64.zip'), '$zipsDest/linux-x64.zip');
  await gscp(p.join(zipsOut, 'symbols.zip'), '$zipsDest/symbols.zip');
  // Maven
  archPath = p.join(archOut, 'x86_64_release');
  mavenPath = '$mavenRoot/x86_64_release/$mavenVer/x86_64_release-$mavenVer';
  await gscp('$archPath.pom', '$mavenPath.pom');
  await gscp('$archPath.jar', '$mavenPath.jar');
  await gscp('$archPath.maven-metadata.xml', '$mavenPath.maven-metadata.xml');

  // Linux host artifacts
  archOut = p.join(outDir, 'host_release');
  // Dart SDK
  final linuxDartZip = p.join(archOut, 'dart-sdk-linux-x64.zip');
  if (await File(linuxDartZip).exists()) {
    await gscp(linuxDartZip, '$infraRoot/dart-sdk-linux-x64.zip');
    if (contentInfraRoot != null) {
      await gscp(linuxDartZip, '$contentInfraRoot/dart-sdk-linux-x64.zip');
    }
  }
  // flutter_patched_sdk_product
  zipsOut = p.join(archOut, 'zip_archives');
  await gscp(p.join(zipsOut, 'flutter_patched_sdk_product.zip'),
      '$infraRoot/flutter_patched_sdk_product.zip');
  // Linux desktop
  zipsOut = p.join(archOut, 'zip_archives', 'linux-x64-release');
  zipsDest = '$infraRoot/linux-x64-release';
  await gscp(p.join(zipsOut, 'linux-x64-flutter-gtk.zip'),
      '$zipsDest/linux-x64-flutter-gtk.zip');
  // Linux artifacts.zip (from host_debug)
  archOut = p.join(outDir, 'host_debug');
  zipsOut = p.join(archOut, 'zip_archives', 'linux-x64');
  zipsDest = '$infraRoot/linux-x64';
  await gscp(p.join(zipsOut, 'artifacts.zip'), '$zipsDest/artifacts.zip');
  // AOT tools
  final aotTools = p.join(outDir, 'host_release', 'aot_tools', 'aot-tools.dill');
  if (await File(aotTools).exists()) {
    await gscp(aotTools, '$shorebirdRoot/aot-tools.dill');
  }

  // =========================================================================
  // macOS artifacts (gen_snapshots, Dart SDK, frameworks)
  // =========================================================================

  // macOS gen_snapshots for Android
  archOut = p.join(outDir, 'android_release_arm64');
  zipsOut = p.join(archOut, 'zip_archives', 'android-arm64-release');
  zipsDest = '$infraRoot/android-arm64-release';
  await gscp(p.join(zipsOut, 'darwin-x64.zip'), '$zipsDest/darwin-x64.zip');

  archOut = p.join(outDir, 'android_release');
  zipsOut = p.join(archOut, 'zip_archives', 'android-arm-release');
  zipsDest = '$infraRoot/android-arm-release';
  await gscp(p.join(zipsOut, 'darwin-x64.zip'), '$zipsDest/darwin-x64.zip');

  archOut = p.join(outDir, 'android_release_x64');
  zipsOut = p.join(archOut, 'zip_archives', 'android-x64-release');
  zipsDest = '$infraRoot/android-x64-release';
  await gscp(p.join(zipsOut, 'darwin-x64.zip'), '$zipsDest/darwin-x64.zip');

  // Dart SDK (macOS x64 and arm64)
  archOut = p.join(outDir, 'host_release');
  var dartZip = p.join(archOut, 'dart-sdk-darwin-x64.zip');
  if (await File(dartZip).exists()) {
    await gscp(dartZip, '$infraRoot/dart-sdk-darwin-x64.zip');
    if (contentInfraRoot != null) {
      await gscp(dartZip, '$contentInfraRoot/dart-sdk-darwin-x64.zip');
    }
  }
  archOut = p.join(outDir, 'host_release_arm64');
  dartZip = p.join(archOut, 'dart-sdk-darwin-arm64.zip');
  if (await File(dartZip).exists()) {
    await gscp(dartZip, '$infraRoot/dart-sdk-darwin-arm64.zip');
    if (contentInfraRoot != null) {
      await gscp(dartZip, '$contentInfraRoot/dart-sdk-darwin-arm64.zip');
    }
  }

  // iOS framework (from compose)
  archOut = p.join(outDir, 'release');
  zipsDest = '$infraRoot/ios-release';
  await gscp(p.join(archOut, 'artifacts.zip'), '$zipsDest/artifacts.zip');
  await gscp(p.join(archOut, 'Flutter.framework.dSYM.zip'),
      '$zipsDest/Flutter.framework.dSYM.zip');

  // macOS framework (from compose)
  zipsOut = p.join(archOut, 'framework');
  zipsDest = '$infraRoot/darwin-x64-release';
  await gscp(p.join(zipsOut, 'framework.zip'), '$zipsDest/framework.zip');
  // macOS gen_snapshot
  zipsOut = p.join(archOut, 'snapshot');
  await gscp(p.join(zipsOut, 'gen_snapshot.zip'), '$zipsDest/gen_snapshot.zip');
  // macOS artifacts.zip (from mac_release_arm64)
  archOut = p.join(outDir, 'mac_release_arm64');
  zipsOut = p.join(archOut, 'zip_archives', 'darwin-arm64-release');
  await gscp(p.join(zipsOut, 'artifacts.zip'), '$zipsDest/artifacts.zip');

  // engine_stamp.json
  final engineStamp = p.join(outDir, 'engine_stamp.json');
  if (await File(engineStamp).exists()) {
    await gscp(engineStamp, '$infraRoot/engine_stamp.json');
  }

  // macOS dSYM
  archOut = p.join(outDir, 'release', 'framework');
  zipsDest = '$infraRoot/darwin-x64';
  final dsym = p.join(archOut, 'FlutterMacOS.framework.dSYM.zip');
  if (await File(dsym).exists()) {
    await gscp(dsym, '$zipsDest/FlutterMacOS.framework.dSYM.zip');
  }

  // =========================================================================
  // Windows artifacts
  // =========================================================================

  // Windows gen_snapshots for Android
  archOut = p.join(outDir, 'android_release_arm64');
  zipsOut = p.join(archOut, 'zip_archives', 'android-arm64-release');
  zipsDest = '$infraRoot/android-arm64-release';
  await gscp(p.join(zipsOut, 'windows-x64.zip'), '$zipsDest/windows-x64.zip');

  archOut = p.join(outDir, 'android_release');
  zipsOut = p.join(archOut, 'zip_archives', 'android-arm-release');
  zipsDest = '$infraRoot/android-arm-release';
  await gscp(p.join(zipsOut, 'windows-x64.zip'), '$zipsDest/windows-x64.zip');

  archOut = p.join(outDir, 'android_release_x64');
  zipsOut = p.join(archOut, 'zip_archives', 'android-x64-release');
  zipsDest = '$infraRoot/android-x64-release';
  await gscp(p.join(zipsOut, 'windows-x64.zip'), '$zipsDest/windows-x64.zip');

  // Windows Dart SDK
  archOut = p.join(outDir, 'host_release');
  dartZip = p.join(archOut, 'dart-sdk-windows-x64.zip');
  if (await File(dartZip).exists()) {
    await gscp(dartZip, '$infraRoot/dart-sdk-windows-x64.zip');
    if (contentInfraRoot != null) {
      await gscp(dartZip, '$contentInfraRoot/dart-sdk-windows-x64.zip');
    }
  }

  // Windows desktop
  archOut = p.join(outDir, 'host_release');
  zipsOut = p.join(archOut, 'zip_archives', 'windows-x64-release');
  zipsDest = '$infraRoot/windows-x64-release';
  await gscp(p.join(zipsOut, 'windows-x64-flutter.zip'),
      '$zipsDest/windows-x64-flutter.zip');
  // Windows artifacts.zip
  archOut = p.join(outDir, 'host_debug');
  zipsOut = p.join(archOut, 'zip_archives', 'windows-x64');
  zipsDest = '$infraRoot/windows-x64';
  await gscp(p.join(zipsOut, 'artifacts.zip'), '$zipsDest/artifacts.zip');

  // =========================================================================
  // Manifest
  // =========================================================================
  final manifestFile = p.join(engineSrc, 'artifacts_manifest.yaml');
  if (await File(manifestFile).exists()) {
    await gscp(manifestFile, '$shorebirdRoot/artifacts_manifest.yaml');
  }

  print('\n[Upload] Production upload complete');
}
